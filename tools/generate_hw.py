#!/usr/bin/env python3
# Generate main/tab5_mesh_hw_dados.cpp from Meshtastic's official HardwareModel
# enum (meshtastic/protobufs, mesh.proto). Run once; afterward it works offline—
# the firmware never looks anything up at runtime.
#
# WHY THIS EXISTS: the previous table was typed by hand with about 12 models
# that seemed likely. In a real mesh (the one that prompted this), actual nodes
# appeared as "model 110", "model 88", and "model 81"—cases the guessed table
# did not cover. The official source has 149 models; generating the full table
# from it eliminates guesswork.
#
#   ./generate_hw.py
#
# See main/tab5_mesh.cpp (mesh_hw_nome) for where the table is used.

import re
import subprocess
import os

URL = "https://raw.githubusercontent.com/meshtastic/protobufs/master/meshtastic/mesh.proto"
PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(PROJECT_ROOT)   # the project root; this script lives in tools/
OUTPUT_PATH = os.path.join(PROJECT_ROOT, "main", "tab5_mesh_hw_dados.cpp")


def make_display_name(enum_name: str) -> str:
    # HELTEC_WIRELESS_TRACKER -> "Heltec Wireless Tracker". No exception
    # dictionary on purpose: the result is derived, not guessed—the same rule
    # that motivated rewriting this file.
    parts = enum_name.split("_")
    display_name = []
    for part in parts:
        if part.isdigit() or re.match(r'^[0-9]', part):
            display_name.append(part)     # "T1000" and "900" remain unchanged
        else:
            display_name.append(part.capitalize())
    return " ".join(display_name)


def main():
    r = subprocess.run(["curl", "-sf", URL], capture_output=True, text=True, check=True)
    txt = r.stdout

    m = re.search(r'enum HardwareModel \{(.*?)\n\}', txt, re.S)
    if not m:
        raise SystemExit("Could not find the HardwareModel enum in mesh.proto—is the format different?")

    entries = re.findall(r'\n\s*([A-Z0-9_]+)\s*=\s*(\d+)\s*;', m.group(1))

    table = {}   # code -> display name
    for enum_name, code_text in entries:
        code = int(code_text)
        if enum_name == "UNSET":
            continue   # 0 means "no information"; handled separately, not named
        if enum_name == "PRIVATE_HW":
            table[code] = "private"
            continue
        table[code] = make_display_name(enum_name)

    lines = [
        "// GENERATED by generate_hw.py from Meshtastic's official HardwareModel",
        "// (meshtastic/protobufs, mesh.proto). Do not edit by hand—",
        "// run the script again if the official list grows.",
        '#include "tab5_mesh.hpp"',
        "",
        "// 256 pointers, mostly null—indexed directly by the code byte, with no",
        "// lookup. Null is meaningful: mesh_hw_nome() returns it so the caller",
        "// can decide how to display a number not yet in the official table.",
        "const char* const TAB5_MESH_HW_NOMES[256] = {",
    ]
    for code in range(256):
        display_name = table.get(code)
        if display_name is None:
            lines.append(f"  [{code}] = nullptr,")
        else:
            lines.append(f'  [{code}] = "{display_name}",')
    lines.append("};")

    with open(OUTPUT_PATH, "w") as output_file:
        output_file.write("\n".join(lines) + "\n")

    print(f"wrote {OUTPUT_PATH}: {len(table)} known models out of {len(entries)} in the enum")


if __name__ == "__main__":
    main()
