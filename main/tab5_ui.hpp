// ------------------------------------------------------------------------
// WHY THIS EXISTS
// ------------------------------------------------------------------------
// tab5_botao() was written byte-for-byte identically in FOUR different
// files in this system (Files, Azimuthal, Settings, Mesh - the Mesh version
// was called "caixa") before being consolidated here. Each copy carried
// the same explanation: "getTextStyle()/setTextStyle() prevents the
// middle_center datum from leaking into subsequent drawing - the SAME trap
// that already affected tab5_power_show". Four different apps had to
// rediscover the same bug, each with its own local workaround.
//
// This is exactly the kind of thing a new app should NOT have to
// learn on its own. If you are writing a button, use tab5_botao(); if
// it always has a bug, the fix applies to every app at once, instead of
// having to remember to update every copy.
//
// See docs/WRITING_APPS.md for the rest of the contract.
#pragma once

#include <M5Unified.h>

// FONT HISTORY: Font0 -> Font4 -> DejaVu24 -> FreeSans12pt7b (all
// 1-bit bitmaps scaled fractionally) -> smoothed Roboto at native sizes
// (below). Titles used FreeMonoBold12pt7b wherever they appeared
// (bar, home screen, app section).

// ------------------------------------------------------------------------
// SMOOTH FONTS - THE END OF JAGGED LETTERS
// ------------------------------------------------------------------------
// Until now, ALL body text used FreeSans12pt7b (1-bit bitmap, 29 px)
// scaled by a fraction - tab5_fonte_size(3.2) = 0.88x, (2.3) = 0.63x.
// Fractional bitmap scaling duplicates some pixel rows and drops
// others: the input bar (0.88x) looked noticeably worse than the
// message bubble (1.05x, almost native size).
//
// Body text now uses SMOOTH Roboto (Apache 2.0) - 8-bit antialiasing,
// VLW format - generated by generate_fonts.py at ~20 NATIVE heights (12 to
// 56 px), regular and bold, including Portuguese accents. tab5_text()
// selects the closest native height to the requested size: no scaling.
//
// tab5_font_body(d);          // or tab5_font_body_bold(d)
// tab5_text(d, 3.2f);          // the SAME number as before (N -> N*8 px)
//
// TITLES still use FreeMonoBold12pt7b (tab5_fonte_title) - intentionally
// monospaced - as does Font0 for fixed-column tables.
void tab5_fontes_start(void); // at boot, before the first drawing
const lgfx::IFont *tab5_fonte_suave(bool bold, int height_px);

// The default body font (the old FreeSans12 height: 29 px -> 28).
#define TAB5_FONTE_CORPO (tab5_fonte_suave(false, 29))
#define TAB5_FONTE_CORPO_ALT_PX 29 // reference height for the "old style" (N*8/29)

// The "old-style" size - only for fonts that are still scaled and are
// NOT the body font (the title). For body text, use tab5_text().
inline float tab5_fonte_size(float legacy_size)
{
  return legacy_size * (8.0f / TAB5_FONTE_CORPO_ALT_PX);
}

// Sets text to size N (height N*8 px) in the current font family: for
// regular or bold body fonts, selects the closest NATIVE height (text size
// 1); for another font (title, Font0), scales it as before.
void tab5_text(lgfx::LovyanGFX &d, float legacy_size);

// Switching font families. setFont() is GLOBAL DISPLAY STATE, not part of
// TextStyle/getTextStyle() - anyone changing it must switch back afterwards:
//
// tab5_source_title(d);
// d.drawString("MESH", cx, cy);
// tab5_font_body(d);
inline void tab5_fonte_titulo(lgfx::LovyanGFX &d) { d.setFont(&fonts::FreeMonoBold12pt7b); }

// SMOOTH TITLE - the SYSTEM title. Bold Roboto at the requested location
// height (px), without scaling: the counterpart to smooth body text, with
// accents. tab5_fonte_title() above (monospaced, 1-bit) remains only for
// the game (the app_cobra folder is untouched - that is its own style).
#define TAB5_TITULO_PX 36 // section/page title
void tab5_titulo(lgfx::LovyanGFX &d, int height_px = TAB5_TITULO_PX);
void tab5_fonte_body(lgfx::LovyanGFX &d);
void tab5_fonte_body_negrito(lgfx::LovyanGFX &d);

// NAMED BUTTON TEXT SIZES. A handful of apps need a larger button label than
// the default; naming the size here (rather than a raw number at each call
// site) means it stays easy to find and adjust for everyone using the name.
// Not a global multiplier - different apps have bumped it by different
// amounts historically, so each call site still picks its own name.
#define TAB5_BOTAO_TEXTO_PADRAO  2.0f
#define TAB5_BOTAO_TEXTO_GRANDE  4.0f

// Grid-line color shared by the Energy and Tasks charts, so both move
// together if it's ever retuned.
#define TAB5_GRAFICO_COR_GRADE  lgfx::color565(64, 64, 78)

// Rounded, filled rectangle with centered text - this system's default
// button. Saves and restores the text style on its own (see tab5_botao's
// warning about TextStyle leaking between draws).
//
//   tab5_botao(d, x, y, width, height, "OK", TFT_SKYBLUE);
//   tab5_botao(d, x, y, width, height, "OK", TFT_SKYBLUE, TFT_WHITE, TAB5_BOTAO_TEXTO_GRANDE);
void tab5_botao(lgfx::LovyanGFX& d, int x, int y, int l, int a,
               const char* txt, uint16_t fundo,
               uint16_t tinta = TFT_BLACK, float tamanho_text = TAB5_BOTAO_TEXTO_PADRAO);

// Panel cell: small label on top, large value below, optional subtitle
// underneath - the same layout used on the home screen (shell.cpp,
// "GROVE"/"CARD") and the Azimuthal position panel.
//
// 'cx' is the cell's horizontal CENTER: with several side by side, each one
// gets the center of its own slice and the text centers itself.
void tab5_celula(lgfx::LovyanGFX& d, int cx, int y0,
                 const char* rotulo, const char* valor, uint16_t color_valor,
                 const char* subtexto = nullptr);

// SMOOTH THICK LINE THAT RESPECTS CLIPPING. Use instead of M5GFX's
// drawWideLine/drawWedgeLine/drawSpot, which swap out the caller's clip
// rect for their own and then clear it afterward (clearClipRect) - inside a
// scrollable list that wipes out everything drawn after it. Same rendering
// here (antialiased edge by distance to the segment, round cap), but every
// pixel goes through whatever clip rect is already in effect. 'r' is the
// radius (half thickness).
void tab5_line_grossa(lgfx::LovyanGFX& d, float x0, float y0, float x1, float y1,
                       float r, uint16_t color);

// Is point (x, y) inside rectangle (rx, ry, rl, ra)? Every button's touch test.
inline bool tab5_dentro(int x, int y, int rx, int ry, int rl, int ra)
{
  return x >= rx && x < rx + rl && y >= ry && y < ry + ra;
}

// Trims text to fit 'max_l' px in whatever font is active on 'd', cutting at
// a UTF-8 character boundary (never mid-character). Binary search over
// measured width (log n measurements). Returns the resulting length in bytes.
size_t tab5_cortar_on_caber(lgfx::LovyanGFX& d, char* t, int max_l);
// Same, ending in "..." when it had to cut ('size' = buffer size).
size_t tab5_cortar_com_reticencias(lgfx::LovyanGFX& d, char* t, size_t size, int max_l);

// SPRITE (M5Canvas) ALWAYS IN PSRAM. Use instead of new M5Canvas +
// createSprite: without setPsram(true), M5GFX requests MALLOC_CAP_DMA, which
// PSRAM doesn't carry on the P4 - the sprite lands in internal SRAM instead
// (a 272x272 16-bit sprite is ~148 KB, half of internal heap). And even with
// setPsram(true), if PSRAM allocation fails M5GFX silently retries internal
// SRAM. Neither happens here: either the buffer is in PSRAM, or this returns
// nullptr and the app carries on without the sprite.
//
// Created in RGB565 (the panel's format) with the body font - a sprite has
// its own text state, separate from the display.
//
//   s_bg = tab5_sprite_novo(&d, w, h);   // nullptr: out of memory
//   tab5_sprite_release(&s_bg);          // frees and zeroes the pointer
M5Canvas* tab5_sprite_novo(lgfx::LovyanGFX* pai, int width, int height);
void      tab5_sprite_release(M5Canvas** sprite);
